"""失败测甲：切流账册——超阈偏钟点装载后，正式入栏行数不得上升。

红条件：
- 超阈点混入可信点一起灌，若入栏缓冲行数把超阈点也算进去则红；
- 偏钟点不带指纹进坏点匣、观测报文命运不标已偏钟则红；
- 偏移阈读取失败时若仍有任何写入（阈值读取与写入命运不共成败）则红。
"""
import pytest

from app.services import 装载, 目录
from app import seed

固定仓时 = "2026-11-25T04:00:00Z"


@pytest.fixture()
def 紧阈(monkeypatch):
    monkeypatch.setattr(seed, "此刻", lambda: 固定仓时)
    目录.改栏规({"站钟漂移阈秒": "300"})


def _混批() -> dict:
    return {
        "批次编号": "甲-混灌",
        "报文": [
            {"报文编号": "A-trust-1", "站点键": "站-河东", "指标键": "PM25", "读数": 22.0,
             "观测时": "2026-11-25T03:59:00Z"},   # 漂 60s，可信
            {"报文编号": "A-trust-2", "站点键": "站-河东", "指标键": "PM25", "读数": 24.0,
             "观测时": "2026-11-25T04:02:00Z"},   # 漂 120s，可信
            {"报文编号": "A-skew-1", "站点键": "站-河东", "指标键": "PM25", "读数": 26.0,
             "观测时": "2026-11-25T01:00:00Z"},   # 漂 10800s，超阈
        ],
    }


def test_超阈点不得进入现行入栏缓冲(紧阈):
    前 = len(目录.缓冲列表())
    报告 = 装载.装一批(_混批())

    # 现行缓冲只涨可信点的两行，超阈点不得混栏
    后 = len(目录.缓冲列表())
    assert 后 - 前 == 2, "超阈偏钟点混进了现行入栏缓冲"
    在栏编号 = {r["报文编号"] for r in 目录.缓冲列表()}
    assert "A-skew-1" not in 在栏编号

    assert 报告["入栏"] == 2
    assert 报告["偏钟"] == 1
    assert 报告["坏点"] == 1


def test_偏钟点带指纹进坏点匣且报文命运标偏钟(紧阈):
    装载.装一批(_混批())

    坏点 = [r for r in 目录.坏点列表() if r["报文编号"] == "A-skew-1"]
    assert len(坏点) == 1
    原因 = 坏点[0]["原因"]
    assert "偏钟" in 原因, "坏点原因未钉偏钟指纹"

    报文 = [r for r in 目录.报文列表() if r["报文编号"] == "A-skew-1"][0]
    assert 报文["命运"] == "已偏钟"

    裁决 = [r for r in 目录.偏移裁决列表() if r["报文编号"] == "A-skew-1"]
    assert len(裁决) == 1
    assert 裁决[0]["是否可信"] in (0, False)
    assert 裁决[0]["指纹"] == 原因, "裁决账册指纹须与坏点匣指纹同票"
    assert 裁决[0]["漂移秒"] == pytest.approx(10800.0)
    assert 裁决[0]["阈值秒"] == pytest.approx(300.0)


def test_可信点与偏钟点同批裁决账册各归各栏(紧阈):
    装载.装一批(_混批())
    裁决 = {r["报文编号"]: r for r in 目录.偏移裁决列表()}
    assert 裁决["A-trust-1"]["是否可信"] in (1, True)
    assert 裁决["A-trust-2"]["是否可信"] in (1, True)
    assert 裁决["A-skew-1"]["是否可信"] in (0, False)


def test_偏移阈损坏则整批失败不写一行业务数据(紧阈):
    conn = 装载.连接()
    conn.execute(
        "INSERT INTO 栏规(键,值) VALUES('站钟漂移阈秒','坏值') "
        "ON CONFLICT(键) DO UPDATE SET 值='坏值'"
    )
    conn.commit()
    conn.close()

    前缓冲 = len(目录.缓冲列表())
    前报文 = len(目录.报文列表())
    前坏点 = len(目录.坏点列表())

    报告 = 装载.装一批(_混批())

    assert any("偏钟" in m.get("说明", "") or "漂移" in m.get("说明", "")
               for m in 报告["明细"]), "阈值损坏须失败闭并给出说明"
    assert 报告["入流"] == 0
    assert len(目录.缓冲列表()) == 前缓冲, "阈读取失败不得写缓冲"
    assert len(目录.报文列表()) == 前报文, "阈读取失败不得写观测报文"
    assert len(目录.坏点列表()) == 前坏点, "阈读取失败不得写坏点匣"
    assert len(目录.偏移裁决列表()) == 0, "阈读取失败不得写裁决账册"
